import {openPage,check,done} from './cdp.mjs';
const W=process.argv[2];
const p=await openPage('file://'+W+'/pages/anim.html', W+'/profile-anim-proj');
const {ev,drag,click,key,send,errors}=p;
const wait=ms=>new Promise(r=>setTimeout(r,ms));
// page helper: build a stored ZIP of n 4x4 frames (colour seed) and load it on a track
await ev(`window.__zip=async(name,n,seed,track)=>{
  const pngs=[];
  for(let f=0;f<n;f++){const c=document.createElement('canvas');c.width=4;c.height=4;const x=c.getContext('2d');x.fillStyle='rgb('+(seed*40)+','+(f*50)+',200)';x.fillRect(0,0,4,4);
    pngs.push(new Uint8Array(await (await new Promise(r=>c.toBlob(r,'image/png'))).arrayBuffer()));}
  const crc=d=>{let c=~0;for(const b of d){c^=b;for(let k=0;k<8;k++)c=c&1?(c>>>1)^0xEDB88320:c>>>1;}return ~c>>>0;};
  const parts=[],cds=[];let off=0;
  pngs.forEach((d,i)=>{const nm=new TextEncoder().encode('frame_'+i+'.png');const h=new DataView(new ArrayBuffer(30));
    h.setUint32(0,0x04034b50,true);h.setUint16(4,20,true);h.setUint32(14,crc(d),true);h.setUint32(18,d.length,true);h.setUint32(22,d.length,true);h.setUint16(26,nm.length,true);
    parts.push(new Uint8Array(h.buffer),nm,d);const c=new DataView(new ArrayBuffer(46));c.setUint32(0,0x02014b50,true);c.setUint16(4,20,true);c.setUint16(6,20,true);
    c.setUint32(16,crc(d),true);c.setUint32(20,d.length,true);c.setUint32(24,d.length,true);c.setUint16(28,nm.length,true);c.setUint32(42,off,true);cds.push(new Uint8Array(c.buffer),nm);off+=30+nm.length+d.length;});
  const cd=cds.reduce((s,b)=>s+b.length,0);const e=new DataView(new ArrayBuffer(22));e.setUint32(0,0x06054b50,true);e.setUint16(8,n,true);e.setUint16(10,n,true);e.setUint32(12,cd,true);e.setUint32(16,off,true);
  await loadZipToTrack(new File([...parts,...cds,new Uint8Array(e.buffer)],name+'.zip'),track);};
  window.__doc=()=>JSON.stringify(state.tracks.map(t=>t.map(s=>[s.name,s.startFrame,s.blend,s.opacity,s.frames.length])));true`);
const doc=()=>ev(`__doc()`);

console.log('Anim Forge — undo');
await ev(`__zip('walk',2,1,0)`); await ev(`__zip('run',3,2,0)`);
check('second segment appended after the first', await doc()===JSON.stringify([[['walk',0,'source-over',1,2],['run',2,'source-over',1,3]],[],[],[]]), await doc());
await key('z',2);
check('Ctrl+Z removes the last loaded segment', await doc()===JSON.stringify([[['walk',0,'source-over',1,2]],[],[],[]]), await doc());
await key('z',2|8);
check('Ctrl+Shift+Z brings it back', (await ev(`state.tracks[0].length`))===2);
await ev(`selectSegment(0,1);true`);
await ev(`(()=>{const el=document.getElementById('p-blend');el.value='lighter';el.dispatchEvent(new Event('change'));})();true`);
check('blend changed', await ev(`state.tracks[0][1].blend`)==='lighter');
await ev(`document.getElementById('undo-btn').click();true`);
check('undo restores blend', await ev(`state.tracks[0][1].blend`)==='source-over');
const u0=await ev(`undoStack.length`);
await ev(`(()=>{const el=document.getElementById('p-name');el.focus();for(const v of ['j','jo','jog']){el.value=v;el.dispatchEvent(new Event('input'));}el.blur();})();true`);
check('typing a name = one undo step', await ev(`undoStack.length`)===u0+1 && await ev(`state.tracks[0][1].name`)==='jog');
await ev(`undo();true`);

console.log('Anim Forge — dragging segments');
const blockAt=i=>ev(`(()=>{const b=document.querySelectorAll('.track-row')[0].querySelectorAll('.seg-block')[${i}].getBoundingClientRect();return [b.left+b.width/2,b.top+b.height/2]})()`);
const z=await ev(`state.zoom`);
const cf=await ev(`state.currentFrame`);
let [bx,by]=await blockAt(1);
await drag(bx,by,bx+5*z,by,8);
check('drag right by 5 frames → start 7', await ev(`state.tracks[0][1].startFrame`)===7, await doc());
check('the click ending the drag did not scrub the playhead', await ev(`state.currentFrame`)===cf);
check('dragged segment is selected', await ev(`document.getElementById('p-name').value`)==='run');
const rowY=await ev(`(()=>{const r=document.querySelectorAll('.track-row')[2].getBoundingClientRect();return r.top+r.height/2})()`);
[bx,by]=await blockAt(1);
await drag(bx,by,bx,rowY,8);
check('drag down → moved to track 3', await doc()===JSON.stringify([[['walk',0,'source-over',1,2]],[],[['run',7,'source-over',1,3]],[]]), await doc());
await ev(`undo();true`);
check('undo → back on track 1', (await ev(`state.tracks[0].length`))===2 && (await ev(`state.tracks[2].length`))===0);
await ev(`undo();true`);
check('undo → back at frame 2', await ev(`state.tracks[0][1].startFrame`)===2);
[bx,by]=await blockAt(0);
await click(bx,by);
check('plain click selects without moving', await ev(`document.getElementById('p-name').value`)==='walk' && await ev(`state.tracks[0][0].startFrame`)===0);
for(const type of ['keyDown','keyUp']) await send('Input.dispatchKeyEvent',{type,key:'Delete',code:'Delete',windowsVirtualKeyCode:46});
check('Delete removes the selected segment', await ev(`state.tracks[0].length`)===1);
await ev(`undo();true`);

console.log('Anim Forge — project save / load');
await ev(`__zip('fx',2,4,1)`);
await ev(`(()=>{const el=document.getElementById('p-opacity');el.value='0';el.dispatchEvent(new Event('change'));
  const f=document.getElementById('fps-input');f.value='12';f.dispatchEvent(new Event('change'));})();true`);
const saved=await doc();
const px=()=>ev(`(()=>{const c=document.createElement('canvas');c.width=4;c.height=4;const x=c.getContext('2d');x.drawImage(state.tracks[1][0].frames[1].img,0,0);return [...x.getImageData(0,0,1,1).data].join()})()`);
const px0=await px();
await ev(`window.__dl=[];const o=URL.createObjectURL;URL.createObjectURL=b=>{__dl.push(b);return o(b);};HTMLAnchorElement.prototype.click=function(){};
  document.getElementById('save-proj-btn').click();true`);
check('project file produced', await ev(`__dl.length===1&&__dl[0].type==='application/json'`));
await ev(`document.getElementById('clear-btn').click();document.getElementById('fps-input').value=30;document.getElementById('fps-input').dispatchEvent(new Event('change'));true`);
check('cleared', await doc()===JSON.stringify([[],[],[],[]]));
await ev(`(async()=>{const dt=new DataTransfer();dt.items.add(new File([__dl[0]],'p.json',{type:'application/json'}));const i=document.getElementById('proj-input');i.files=dt.files;i.dispatchEvent(new Event('change'));await new Promise(r=>setTimeout(r,800));})()`);
check('segments restored exactly (incl. opacity 0)', await doc()===saved, (await doc())+' vs '+saved);
check('frame pixels restored', await px()===px0, await px()+' vs '+px0);
check('FPS restored', await ev(`state.fps===12&&document.getElementById('fps-input').value==='12'`));
check('history reset after load', await ev(`undoStack.length===0&&document.getElementById('undo-btn').disabled`));
check('no page exceptions', errors.length===0, errors.join(' | '));
p.close(); done();
