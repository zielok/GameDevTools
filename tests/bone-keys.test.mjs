import {openPage,check,done} from './cdp.mjs';
const SP=process.argv[2], page=process.argv[3]||'bone.html';
const p=await openPage('file://'+SP+'/pages/'+page, SP+'/profile-bonek-'+page);
const {ev,key,send,errors}=p;
const press=async(k,code,vk)=>{for(const type of ['keyDown','keyUp'])await send('Input.dispatchKeyEvent',{type,key:k,code,windowsVirtualKeyCode:vk});};
console.log('Bone Forge — shortcuts ('+page+')');
await ev(`addBone(null);addBone(null);true`);
check('2 bones', await ev(`S.bones.length`)===2);
await key('z',2);
check('Ctrl+Z undoes bone #2', await ev(`S.bones.length`)===1);
await key('z',2|8);
check('Ctrl+Shift+Z redoes it', await ev(`S.bones.length`)===2, await ev(`S.bones.length`));
await ev(`S.selBone=S.bones[1].id;S.mode='ik';setModeBtns();true`);
await key('v',2);
check('Ctrl+V keeps the current mode', await ev(`S.mode`)==='ik', await ev(`S.mode`));
await key('v');
check('plain V still switches to Select', await ev(`S.mode`)==='sel');
await press('Backspace','Backspace',8);
check('Backspace (Mac "delete") deletes the selected bone', await ev(`S.bones.length`)===1, await ev(`S.bones.length`));
check('no page exceptions', errors.length===0, errors.join(' | '));
p.close(); done();
